fn validate_auth_options(c: &Collection, original: Option<&Collection>) -> Option<Node> {
    // Missing option keys (e.g. a base collection being type-changed to auth)
    // are treated as their zero value, so every field fails validation.
    let mut opts = c.options.clone();
    if let Some(obj) = opts.as_object_mut() {
        for key in AUTH_OPTION_KEYS {
            obj.entry((*key).to_string())
                .or_insert_with(|| zero_option(key));
        }
    }
    let options = &opts;
    let mut errs = Errors::new();

    // authRule / manageRule: only the NilOrNotEmpty rule is checkable without
    // the filter parser (D9). System collections cannot change their rules.
    if let Some(original) = original {
        if original.system {
            for key in ["authRule", "manageRule"] {
                let new_val = options.get(key).cloned();
                let old_val = original.options.get(key).cloned();
                if new_val != old_val {
                    errs.insert(
                        key.into(),
                        validation::leaf(
                            "validation_collection_system_rule_change",
                            "System collection API rule cannot be changed.",
                        ),
                    );
                }
            }
        }
    }
    if let Some(Value::String(rule)) = options.get("manageRule") {
        if rule.is_empty() {
            errs.insert(
                "manageRule".into(),
                validation::leaf("validation_nil_or_not_empty_required", "cannot be blank"),
            );
        }
    }

    if let Some(alert) = options.get("authAlert") {
        if let Some(err) = validate_email_template(alert.get("emailTemplate")) {
            errs.insert("authAlert".into(), wrap("emailTemplate", err));
        }
    }

    if let Some(password_auth) = options.get("passwordAuth") {
        if password_auth
            .get("enabled")
            .and_then(Value::as_bool)
            .unwrap_or(false)
        {
            let identity = password_auth.get("identityFields").and_then(Value::as_array);
            let empty = identity.map(|items| items.is_empty()).unwrap_or(true);
            if empty {
                errs.insert(
                    "passwordAuth".into(),
                    wrap("identityFields", validation::required()),
                );
            } else if let Some(err) = check_identity_fields(identity.unwrap(), c) {
                errs.insert("passwordAuth".into(), wrap("identityFields", err));
            }
        }
    }

    if let Some(oauth2) = options.get("oauth2") {
        if oauth2
            .get("enabled")
            .and_then(Value::as_bool)
            .unwrap_or(false)
        {
            // `ValidateStruct(&OAuth2Config)` nests the rule error under
            // the `providers` field.
            if let Some(err) = check_duplicated_providers(oauth2.get("providers")) {
                errs.insert("oauth2".into(), wrap("providers", err));
            }
        }
    }

    if let Some(otp) = options.get("otp") {
        let enabled = otp.get("enabled").and_then(Value::as_bool).unwrap_or(false);
        let mut inner = Errors::new();
        if enabled {
            let duration = otp.get("duration").and_then(Value::as_i64).unwrap_or(0);
            if let Some(err) = required_then(duration, |v| {
                validation::min(v, 10).or_else(|| validation::max(v, 86400))
            }) {
                inner.insert("duration".into(), err);
            }
            let length = otp.get("length").and_then(Value::as_i64).unwrap_or(0);
            if let Some(err) = required_then(length, |v| validation::min(v, 4)) {
                inner.insert("length".into(), err);
            }
        }
        if let Some(err) = validate_email_template(otp.get("emailTemplate")) {
            inner.insert("emailTemplate".into(), err);
        }
        if let Some(err) = validation::branch(inner) {
            errs.insert("otp".into(), err);
        }
    }

    if let Some(mfa) = options.get("mfa") {
        let enabled = mfa.get("enabled").and_then(Value::as_bool).unwrap_or(false);
        if enabled {
            let duration = mfa.get("duration").and_then(Value::as_i64).unwrap_or(0);
            if let Some(err) = required_then(duration, |v| {
                validation::min(v, 10).or_else(|| validation::max(v, 86400))
            }) {
                errs.insert("mfa".into(), wrap("duration", err));
            }
        }
        if let Some(original) = original {
            if original.system {
                let new_rule = mfa.get("rule").and_then(Value::as_str).unwrap_or("");
                let old_rule = original
                    .options
                    .get("mfa")
                    .and_then(|v| v.get("rule"))
                    .and_then(Value::as_str)
                    .unwrap_or("");
                if new_rule != old_rule {
                    errs.insert(
                        "mfa".into(),
                        wrap(
                            "rule",
                            validation::leaf(
                                "validation_collection_system_rule_change",
                                "System collection API rule cannot be changed.",
                            ),
                        ),
                    );
                }
            }
        }
    }

    for key in [
        "authToken",
        "passwordResetToken",
        "emailChangeToken",
        "verificationToken",
        "fileToken",
    ] {
        if let Some(config) = options.get(key) {
            if let Some(err) = validate_token_config(config) {
                errs.insert(key.into(), err);
            }
        }
    }

    for key in [
        "verificationTemplate",
        "resetPasswordTemplate",
        "confirmEmailChangeTemplate",
    ] {
        if let Some(err) = validate_email_template(options.get(key)) {
            errs.insert(key.into(), err);
        }
    }

    if let Some(err) = validation::branch(errs) {
        return Some(err);
    }

    // MFA enabled requires at least 2 auth methods.
    let enabled = |key: &str| {
        options
            .get(key)
            .and_then(|v| v.get("enabled"))
            .and_then(Value::as_bool)
            .unwrap_or(false)
    };
    if enabled("mfa") {
        let total = ["passwordAuth", "oauth2", "otp"]
            .iter()
            .filter(|key| enabled(key))
            .count();
        if total < 2 {
            let mut inner = Errors::new();
            inner.insert(
                "enabled".into(),
                validation::leaf(
                    "validation_mfa_not_enough_auths",
                    "MFA requires at least 2 auth methods to be enabled.",
                ),
            );
            let mut errs = Errors::new();
            errs.insert("mfa".into(), Node::Branch(inner));
            return validation::branch(errs);
        }
    }

    None
}

fn wrap(key: &str, node: Node) -> Node {
    let mut errs = Errors::new();
    errs.insert(key.to_string(), node);
    Node::Branch(errs)
}

fn required_then(value: i64, then: impl FnOnce(i64) -> Option<Node>) -> Option<Node> {
    if value == 0 {
        return Some(validation::required());
    }
    then(value)
}

fn validate_email_template(template: Option<&Value>) -> Option<Node> {
    let Some(template) = template else {
        return None;
    };
    let mut errs = Errors::new();
    for key in ["subject", "body"] {
        let value = template.get(key).and_then(Value::as_str).unwrap_or("");
        if value.is_empty() {
            errs.insert(key.into(), validation::required());
        }
    }
    validation::branch(errs)
}

fn validate_token_config(config: &Value) -> Option<Node> {
    let mut errs = Errors::new();
    let secret = config.get("secret").and_then(Value::as_str).unwrap_or("");
    if secret.is_empty() {
        errs.insert("secret".into(), validation::required());
    } else if let Some(err) = validation::length(secret, 30, 255) {
        errs.insert("secret".into(), err);
    }
    let duration = config.get("duration").and_then(Value::as_i64).unwrap_or(0);
    if let Some(err) = required_then(duration, |v| {
        validation::min(v, 10).or_else(|| validation::max(v, 94_670_856))
    }) {
        errs.insert("duration".into(), err);
    }
    validation::branch(errs)
}

fn check_duplicated_providers(providers: Option<&Value>) -> Option<Node> {
    let Some(providers) = providers.and_then(Value::as_array) else {
        return None;
    };
    let mut seen: Vec<String> = Vec::new();
    let mut errs = Errors::new();
    for (i, provider) in providers.iter().enumerate() {
        let name = provider.get("name").and_then(Value::as_str).unwrap_or("");
        if name.is_empty() {
            continue;
        }
        if seen.contains(&name.to_string()) {
            errs.insert(
                i.to_string(),
                wrap(
                    "name",
                    validation::leaf_with_params(
                        "validation_duplicated_provider",
                        "The provider {{.name}} is already registered.",
                        json!({ "name": name }),
                    ),
                ),
            );
            return validation::branch(errs);
        }
        seen.push(name.to_string());
    }
    None
}

fn check_identity_fields(identity: &[Value], c: &Collection) -> Option<Node> {
    let indexes = c.index_list();
    for item in identity {
        let name = item.as_str().unwrap_or("");
        let Some(field) = c.field_list().get_by_name(name).cloned() else {
            return Some(validation::leaf_with_params(
                "validation_missing_field",
                "Invalid or missing field {{.fieldName}}",
                json!({ "fieldName": name }),
            ));
        };
        let _ = field;
        if schema_sync::find_single_column_unique_index(&indexes, name).is_none() {
            return Some(validation::leaf_with_params(
                "validation_missing_unique_constraint",
                "The field {{.fieldName}} doesn't have a UNIQUE constraint.",
                json!({ "fieldName": name }),
            ));
        }
    }
    None
}

