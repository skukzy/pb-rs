    #[test]
    fn delete_reports_system_and_reference_errors() {
        let mut conn = fresh();
        let all = Collection::load_all(&conn).unwrap();
        let superusers = all.iter().find(|c| c.name == "_superusers").unwrap();
        assert!(delete(&mut conn, superusers).is_err());

        let target = create(&mut conn, json!({"type": "base", "name": "target"})).unwrap();
        create(
            &mut conn,
            json!({
                "type": "base",
                "name": "referrer",
                "fields": [{"name": "r", "type": "relation", "collectionId": target.id}],
            }),
        )
        .unwrap();
        let all = Collection::load_all(&conn).unwrap();
        assert_eq!(find_references(&target, &all), vec!["referrer".to_string()]);

        // Relation references block the delete (`onCollectionDeleteExecute`).
        assert!(delete(&mut conn, &target).is_err());

        let referrer = Collection::find(&conn, "referrer").unwrap().unwrap();
        delete(&mut conn, &referrer).unwrap();
        delete(&mut conn, &target).unwrap();
        assert!(Collection::find(&conn, "target").unwrap().is_none());
    }

    #[test]
    fn truncate_rejects_views_and_guards_the_last_superuser() {
        let mut conn = fresh();
        let all = Collection::load_all(&conn).unwrap();
        let view = factory("view", "v").collection;
        assert!(truncate(&mut conn, &view).is_err());

        let superusers = all.iter().find(|c| c.name == "_superusers").unwrap();
        // The guard fires per deleted record, so it only trips with a row.
        conn.execute(
            "INSERT INTO _superusers (id, email, password, tokenKey) VALUES ('s1', 'a@b.com', 'x', 'k')",
            [],
        )
        .unwrap();
        assert!(truncate(&mut conn, superusers).is_err());

        let base = create(&mut conn, json!({"type": "base", "name": "trunc"})).unwrap();
        truncate(&mut conn, &base).unwrap();
    }
