//! Collection write pipeline (`apis/collection.go`).
//!
//! The oracle saves a collection through three hooks and this module mirrors
//! that order exactly:
//!
//! 1. `onCollectionSave` — type fallback, id/timestamps, `NewFieldsList`,
//!    `initDefaultFields`, OAuth2 mapped-field cleanup, generated-id collision
//!    handling and index table-name normalization;
//! 2. `onCollectionValidate` — the ozzo error tree;
//! 3. `onCollectionSaveExecute` — records table/view sync + the `_collections`
//!    row write.
//!
//! Only the JSON request binding is implemented (form/multipart bodies are
//! handled by the API layer as a no-op, like the settings endpoint).

use rusqlite::Connection;
use serde_json::{json, Map, Value};

use crate::collections::{Collection, TYPE_AUTH, TYPE_BASE, TYPE_VIEW, AUTH_OPTION_KEYS};
use crate::fields::{self, BindError, FieldsList};
use crate::ids;
use crate::schema_sync;
use crate::search;
use crate::validation::{self, Errors, Node};
use crate::view;

/// A collection being created, plus the factory bookkeeping the oracle keeps
/// in the unexported `autogeneratedId` field.
#[derive(Debug, Clone)]
pub struct Draft {
    pub collection: Collection,
    pub autogenerated_id: String,
}

/// Why a save failed. The API layer maps each variant to the oracle's message.
#[derive(Debug)]
pub enum SaveError {
    /// A database failure that is not a validation error.
    Raw(String),
    /// The collection disappeared during the save (e.g. its id was changed).
    NotFound,
    /// An ozzo validation tree.
    Validation(Errors),
}

/// `core.NewCollection(type, name)`.
pub fn factory(kind: &str, name: &str) -> Draft {
    let kind = match kind {
        TYPE_AUTH => TYPE_AUTH,
        TYPE_VIEW => TYPE_VIEW,
        _ => TYPE_BASE,
    };

    let mut collection = Collection {
        id: id_checksum(kind, name),
        system: false,
        kind: kind.to_string(),
        name: name.to_string(),
        fields: Value::Array(vec![]),
        indexes: Value::Array(vec![]),
        list_rule: None,
        view_rule: None,
        create_rule: None,
        update_rule: None,
        delete_rule: None,
        options: Value::Object(Map::new()),
        created: String::new(),
        updated: String::new(),
    };
    let autogenerated_id = collection.id.clone();

    if kind == TYPE_AUTH {
        collection.options = auth_options_default();
    }

    let mut list = FieldsList::new();
    init_default_fields(&mut collection, &mut list);
    collection.fields = list.to_json();

    Draft {
        collection,
        autogenerated_id,
    }
}

/// `c.idChecksum()`.
fn id_checksum(kind: &str, name: &str) -> String {
    format!("pbc_{}", ids::crc32(&format!("{kind}{name}")))
}

/// `apis/collection.go: collectionCreate`'s first bind step.
pub fn factory_extract(body: &Value) -> Result<(String, String), BindError> {
    let obj = match body {
        Value::Null => return Ok((String::new(), String::new())),
        Value::Object(obj) => obj,
        _ => return Err(BindError),
    };
    let mut kind = String::new();
    let mut name = String::new();
    for (key, value) in obj {
        match key.as_str() {
            "type" | "name" => {
                let bound = bind_string(value)?;
                if key == "type" {
                    kind = bound;
                } else {
                    name = bound;
                }
            }
            _ => {}
        }
    }
    Ok((kind, name))
}

/// `e.BindBody(collection)`: `json.Unmarshal` onto the factory model.
///
/// Go semantics: `null` is a no-op for every target, unknown keys are ignored
/// and a type mismatch aborts the whole bind.
pub fn apply_request(draft: &mut Draft, body: &Value) -> Result<(), BindError> {
    if body.is_null() {
        return Ok(());
    }
    let obj = body.as_object().ok_or(BindError)?;
    let c = &mut draft.collection;

    for (key, value) in obj {
        match key.as_str() {
            // `encoding/json/v2` zeroes the target for a JSON `null` (it is
            // *not* the v1 no-op), so `null` clears the scaffold value.
            "id" | "name" | "type" => {
                let bound = bind_string(value)?;
                match key.as_str() {
                    "id" => c.id = bound,
                    "name" => c.name = bound,
                    _ => c.kind = bound,
                }
            }
            "system" => c.system = bind_bool(value)?,
            // Slices and maps are set to nil by `null` (and nil marshals as
            // `[]` / `{}` with the oracle's json/v2 configuration).
            "fields" => {
                let list = if value.is_null() {
                    FieldsList::new()
                } else {
                    FieldsList::from_request(value)?
                };
                c.fields = list.to_json();
            }
            "indexes" => c.indexes = bind_string_array(value)?,
            // `*string`: `null` is a nil pointer.
            "listRule" => c.list_rule = bind_opt_string(value)?,
            "viewRule" => c.view_rule = bind_opt_string(value)?,
            "createRule" => c.create_rule = bind_opt_string(value)?,
            "updateRule" => c.update_rule = bind_opt_string(value)?,
            "deleteRule" => c.delete_rule = bind_opt_string(value)?,
            // `types.DateTime`: `null` collapses to the zero value, which the
            // save hook overwrites anyway.
            "created" | "updated" => {
                let bound = bind_datetime(value)?;
                if key == "created" {
                    c.created = bound;
                } else {
                    c.updated = bound;
                }
            }
            // The `Collection` struct embeds both option structs, so the
            // binding is independent of the submitted `type` (which may appear
            // later in the object).
            "viewQuery" => set_option(c, "viewQuery", Value::String(bind_string(value)?)),
            "authRule" | "manageRule" | "authAlert" | "oauth2" | "passwordAuth" | "mfa"
            | "otp" | "authToken" | "passwordResetToken" | "emailChangeToken"
            | "verificationToken" | "fileToken" | "verificationTemplate"
            | "resetPasswordTemplate" | "confirmEmailChangeTemplate" => {
                ensure_auth_options(c);
                bind_auth_option(c, key, value)?;
            }
            _ => {}
        }
    }

    Ok(())
}

fn bind_string(value: &Value) -> Result<String, BindError> {
    match value {
        // json/v2 zeroes the target for `null`.
        Value::Null => Ok(String::new()),
        Value::String(s) => Ok(s.clone()),
        _ => Err(BindError),
    }
}

fn bind_bool(value: &Value) -> Result<bool, BindError> {
    match value {
        Value::Null => Ok(false),
        Value::Bool(b) => Ok(*b),
        _ => Err(BindError),
    }
}

fn bind_i64(value: &Value) -> Result<i64, BindError> {
    match value {
        Value::Null => Ok(0),
        Value::Number(n) => n.as_i64().ok_or(BindError),
        _ => Err(BindError),
    }
}

fn bind_opt_string(value: &Value) -> Result<Option<String>, BindError> {
    match value {
        Value::Null => Ok(None),
        Value::String(s) => Ok(Some(s.clone())),
        _ => Err(BindError),
    }
}

fn bind_string_array(value: &Value) -> Result<Value, BindError> {
    match value {
        Value::Null => Ok(Value::Array(vec![])),
        Value::Array(items) => items
            .iter()
            .map(|item| match item {
                Value::String(s) => Ok(Value::String(s.clone())),
                _ => Err(BindError),
            })
            .collect::<Result<Vec<_>, _>>()
            .map(Value::Array),
        _ => Err(BindError),
    }
}

/// `types.DateTime.UnmarshalJSON` (`null` -> zero value).
fn bind_datetime(value: &Value) -> Result<String, BindError> {
    match value {
        Value::Null => Ok(String::new()),
        Value::String(raw) => Ok(fields::normalize_date(raw)),
        _ => Err(BindError),
    }
}

