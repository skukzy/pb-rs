fn bind_oauth2(target: &mut Value, value: &Value) -> Result<(), BindError> {
    if value.is_null() {
        *target = zero_option("oauth2");
        return Ok(());
    }
    let source = as_object(value)?;
    for (key, raw) in source {
        match key.as_str() {
            "enabled" => {
                if let Some(obj) = target.as_object_mut() {
                    obj.insert("enabled".into(), Value::Bool(bind_bool(raw)?));
                }
            }
            "mappedFields" => {
                if let Some(mapped) = target.get_mut("mappedFields") {
                    if raw.is_null() {
                        *mapped = zero_option("oauth2")["mappedFields"].clone();
                    } else {
                        merge_struct(mapped, raw, &[])?;
                    }
                }
            }
            "providers" => {
                let providers = bind_providers(raw, target.get("providers"))?;
                if let Some(obj) = target.as_object_mut() {
                    obj.insert("providers".into(), providers);
                }
            }
            _ => {}
        }
    }
    Ok(())
}

/// `OAuth2Config.UnmarshalJSON`: providers are merged per name with the
/// previously stored config, so a partial provider keeps its secret.
fn bind_providers(raw: &Value, original: Option<&Value>) -> Result<Value, BindError> {
    let items = match raw {
        Value::Null => return Ok(Value::Array(vec![])),
        Value::Array(items) => items,
        _ => return Err(BindError),
    };
    let originals: Vec<Value> = original
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();

    let mut out = Vec::with_capacity(items.len());
    for item in items {
        let source = as_object(item)?;
        let name = match source.get("name") {
            None | Some(Value::Null) => String::new(),
            Some(value) => bind_string(value)?,
        };
        let base = originals
            .iter()
            .find(|provider| provider.get("name").and_then(Value::as_str) == Some(name.as_str()))
            .cloned()
            .unwrap_or_else(provider_zero);
        out.push(bind_provider(base, source)?);
    }
    Ok(Value::Array(out))
}

/// `OAuth2ProviderConfig` zero value (json/v2 marshals nil slices/maps as
/// `[]`/`{}`).
fn provider_zero() -> Value {
    json!({
        "pkce": null,
        "name": "",
        "clientId": "",
        "authURL": "",
        "tokenURL": "",
        "userInfoURL": "",
        "displayName": "",
        "extra": {},
    })
}

fn bind_provider(mut target: Value, source: &Map<String, Value>) -> Result<Value, BindError> {
    for (key, raw) in source {
        match key.as_str() {
            "pkce" => {
                let value = match raw {
                    Value::Null => Value::Null,
                    Value::Bool(b) => Value::Bool(*b),
                    _ => return Err(BindError),
                };
                target["pkce"] = value;
            }
            "name" | "clientId" | "clientSecret" | "authURL" | "tokenURL" | "userInfoURL"
            | "displayName" => {
                target[key.as_str()] = Value::String(bind_string(raw)?);
            }
            "extra" => {
                let value = match raw {
                    Value::Null => json!({}),
                    Value::Object(obj) => Value::Object(obj.clone()),
                    _ => return Err(BindError),
                };
                target["extra"] = value;
            }
            _ => {}
        }
    }
    Ok(provider_canonical(target))
}

/// Rebuild a provider in Go's struct field order so the stored `options` JSON
/// is byte-identical (`clientSecret` is `omitempty`, so it only appears when
/// set, but it must keep its position after `clientId`).
fn provider_canonical(target: Value) -> Value {
    let mut out = Map::new();
    for key in [
        "pkce",
        "name",
        "clientId",
        "clientSecret",
        "authURL",
        "tokenURL",
        "userInfoURL",
        "displayName",
        "extra",
    ] {
        match key {
            "clientSecret" => {
                if let Some(secret) = target.get(key).and_then(Value::as_str) {
                    if !secret.is_empty() {
                        out.insert(key.into(), Value::String(secret.to_string()));
                    }
                }
            }
            _ => {
                if let Some(value) = target.get(key) {
                    out.insert(key.into(), value.clone());
                }
            }
        }
    }
    Value::Object(out)
}

