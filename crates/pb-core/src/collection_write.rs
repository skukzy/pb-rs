/// `onCollectionValidate` for a new collection.
pub fn validate(conn: &Connection, c: &Collection, all: &[Collection]) -> Errors {
    validate_inner(conn, c, None, all)
}

pub fn validate_update(
    conn: &Connection,
    c: &Collection,
    original: &Collection,
    all: &[Collection],
) -> Errors {
    // Mirrors the oracle: `onCollectionValidate` reloads the original by the
    // (possibly changed) id, so a changed id is treated as a new collection.
    let effective = if c.id == original.id {
        Some(original)
    } else {
        None
    };
    validate_inner(conn, c, effective, all)
}

fn validate_inner(
    conn: &Connection,
    c: &Collection,
    original: Option<&Collection>,
    all: &[Collection],
) -> Errors {
    let mut errs = Errors::new();

    // Id
    if let Some(original) = original {
        if c.id != original.id {
            validation::push(
                &mut errs,
                "id",
                Some(validation::leaf(
                    "validation_values_mismatch",
                    "Values don't match.",
                )),
            );
        }
    } else if c.id.is_empty() {
        validation::push(&mut errs, "id", Some(validation::required()));
    } else if let Some(err) = validation::length(&c.id, 1, 100) {
        validation::push(&mut errs, "id", Some(err));
    } else if !is_word(&c.id) {
        validation::push(
            &mut errs,
            "id",
            Some(validation::leaf(
                "validation_match_invalid",
                "must be in a valid format",
            )),
        );
    } else if all.iter().any(|other| other.id == c.id) {
        validation::push(
            &mut errs,
            "id",
            Some(validation::leaf(
                "validation_invalid_or_existing_id",
                "The model id is invalid or already exists.",
            )),
        );
    }

    // System flag
    if let Some(original) = original {
        if c.system != original.system {
            validation::push(
                &mut errs,
                "system",
                Some(validation::leaf(
                    "validation_collection_system_flag_change",
                    "System collection state cannot be changed.",
                )),
            );
        }
    }

    // Type
    if c.kind.is_empty() {
        validation::push(&mut errs, "type", Some(validation::required()));
    } else if ![TYPE_BASE, TYPE_AUTH, TYPE_VIEW].contains(&c.kind.as_str()) {
        validation::push(&mut errs, "type", Some(validation::invalid_in()));
    }
    if let Some(original) = original {
        if c.kind != original.kind {
            validation::push(
                &mut errs,
                "type",
                Some(validation::leaf(
                    "validation_collection_type_change",
                    "Collection type cannot be changed.",
                )),
            );
        }
    }

    // Name
    validation::push(&mut errs, "name", validate_collection_name(conn, c, all, original));

    // Fields
    let list = c.field_list();
    let fields_err = validate_fields(&list, c, all, original);
    if let Some(err) = fields_err {
        errs.insert("fields".into(), err);
    }

    // View collections must not define create/update/delete rules.
    if c.kind == TYPE_VIEW {
        for (key, rule) in [
            ("createRule", &c.create_rule),
            ("updateRule", &c.update_rule),
            ("deleteRule", &c.delete_rule),
        ] {
            if rule.is_some() {
                errs.insert(
                    key.into(),
                    validation::leaf("validation_nil", "must be blank"),
                );
            }
        }
    }

    // API rules: the filter parser is not ported yet (D9). For updates on
    // system collections, the system-rule guard fires.
    if let Some(original) = original {
        if original.system {
            let rules = [
                ("listRule", &c.list_rule, &original.list_rule),
                ("viewRule", &c.view_rule, &original.view_rule),
                ("createRule", &c.create_rule, &original.create_rule),
                ("updateRule", &c.update_rule, &original.update_rule),
                ("deleteRule", &c.delete_rule, &original.delete_rule),
            ];
            for (key, new_val, old_val) in rules {
                if new_val != old_val {
                    validation::push(
                        &mut errs,
                        key,
                        Some(validation::leaf(
                            "validation_collection_system_rule_change",
                            "System collection API rule cannot be changed.",
                        )),
                    );
                }
            }
        }
    }

    // API rules: validate each non-empty rule expression against the collection
    // schema (mirrors `collectionValidator.checkRule`).
    let rules_to_check = [
        ("listRule", &c.list_rule),
        ("viewRule", &c.view_rule),
        ("createRule", &c.create_rule),
        ("updateRule", &c.update_rule),
        ("deleteRule", &c.delete_rule),
    ];
    for (key, rule) in rules_to_check {
        if let Some(rule) = rule {
            if !rule.trim().is_empty() {
                if let Err(err) = validate_rule(c, rule, all) {
                    validation::push(
                        &mut errs,
                        key,
                        Some(validation::leaf(
                            "validation_invalid_rule",
                            format!("Invalid rule. Raw error: {err}"),
                        )),
                    );
                }
            }
        }
    }

    // Indexes
    if let Some(err) = validate_indexes(conn, c, original) {
        errs.insert("indexes".into(), err);
    }

    // Type specific options
    match c.kind.as_str() {
        TYPE_AUTH => {
            if let Some(err) = validate_auth_options(c, original) {
                errs.insert("auth".into(), err);
            }
        }
        TYPE_VIEW => {
            // `collectionViewOptions.validate`: ViewQuery Required + DryRunView.
            let query = view_query(c);
            let mut inner = Errors::new();
            if query.is_empty() {
                inner.insert("viewQuery".into(), validation::required());
            } else if let Err(err) = view::dry_run(conn, query, 10) {
                // `checkViewQuery` truncates the raw error to 500 bytes.
                let raw = if err.len() > 500 {
                    String::from_utf8_lossy(&err.as_bytes()[..500]).into_owned()
                } else {
                    err
                };
                inner.insert(
                    "viewQuery".into(),
                    validation::leaf(
                        "validation_invalid_view_query",
                        format!("Invalid query - {raw}"),
                    ),
                );
            }
            if let Some(err) = validation::branch(inner) {
                errs.insert("view".into(), err);
            }
        }
        _ => {}
    }

    // `JoinValidationErrors` flattens the option errors back into the same map.
    for key in ["auth", "view"] {
        if let Some(Node::Branch(inner)) = errs.remove(key) {
            for (k, v) in inner {
                errs.insert(k, v);
            }
        }
    }

    errs
}

fn is_word(value: &str) -> bool {
    !value.is_empty()
        && value
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_')
}

/// `collectionNameRegex` is Go's `^\w+$`.
fn validate_collection_name(
    conn: &Connection,
    c: &Collection,
    all: &[Collection],
    original: Option<&Collection>,
) -> Option<Node> {
    // System name change guard.
    if let Some(original) = original {
        if original.system && c.name != original.name {
            return Some(validation::leaf(
                "validation_collection_system_name_change",
                "System collection name cannot be changed.",
            ));
        }
    }

    let name = c.name.as_str();
    if name.is_empty() {
        return Some(validation::required());
    }
    if let Some(err) = validation::length(name, 1, 255) {
        return Some(err);
    }
    if name.to_lowercase().contains("_via_") {
        return Some(validation::leaf(
            "validation_found_via",
            "The value cannot contain \"_via_\".",
        ));
    }
    if !is_word(name) {
        return Some(validation::leaf(
            "validation_match_invalid",
            "must be in a valid format",
        ));
    }

    // `checkUniqueName`
    let exclude_id = original
        .map(|o| o.id.clone())
        .unwrap_or_else(|| id_checksum(&c.kind, ""));
    let unique = |exclude: Option<&str>| {
        !all.iter()
            .any(|other| other.name.eq_ignore_ascii_case(name) && Some(other.id.as_str()) != exclude)
    };
    if !unique(Some(exclude_id.as_str())) {
        return Some(validation::leaf(
            "validation_collection_name_exists",
            "Collection name must be unique (case insensitive).",
        ));
    }
    if all.iter().any(|other| other.id == name) {
        return Some(validation::leaf(
            "validation_collection_name_id_duplicate",
            "The name must not match an existing collection id.",
        ));
    }
    let name_changed = original.map(|o| o.name != name).unwrap_or(true);
    if name_changed && unique(None) && has_table(conn, name) {
        return Some(validation::leaf(
            "validation_collection_name_invalid",
            "The name shouldn't match with an existing internal table.",
        ));
    }
    None
}

fn has_table(conn: &Connection, name: &str) -> bool {
    conn.query_row(
        "SELECT (1) FROM sqlite_schema
         WHERE type IN ('table','view') AND LOWER(name)=LOWER(?1) LIMIT 1",
        [name],
        |row| row.get::<_, i64>(0),
    )
    .is_ok()
}

fn validate_fields(
    list: &FieldsList,
    c: &Collection,
    all: &[Collection],
    original: Option<&Collection>,
) -> Option<Node> {
    if let Some(err) = check_field_duplicates(list) {
        return Some(err);
    }
    if let Some(err) = check_min_fields(list, c) {
        return Some(err);
    }

    if c.kind != TYPE_VIEW {
        if let Some(original) = original {
            // ensureNoSystemFieldsChange
            for old_field in original.field_list().items() {
                if !fields::field_bool(old_field, "system") {
                    continue;
                }
                let found = list
                    .get_by_id(fields::field_id(old_field))
                    .map(|f| fields::field_name(f) == fields::field_name(old_field))
                    .unwrap_or(false);
                if !found {
                    return Some(validation::leaf(
                        "validation_system_field_change",
                        "System fields cannot be deleted or renamed.",
                    ));
                }
            }
            // ensureNoFieldsTypeChange
            let mut errs = Errors::new();
            for (i, field) in list.items().iter().enumerate() {
                let id = fields::field_id(field);
                if let Some(old_field) = original.field_list().get_by_id(id) {
                    if fields::field_type(old_field) != fields::field_type(field) {
                        errs.insert(
                            i.to_string(),
                            validation::leaf("validation_field_type_change", "Field type cannot be changed."),
                        );
                    }
                }
            }
            if let Some(err) = validation::branch(errs) {
                return Some(err);
            }
        } else {
            let original_fields = factory_fields(&c.kind);
            let mut errs = Errors::new();
            for (i, field) in list.items().iter().enumerate() {
                let id = fields::field_id(field);
                if let Some(old) = original_fields.iter().find(|o| fields::field_id(o) == id) {
                    if fields::field_type(old) != fields::field_type(field) {
                        errs.insert(
                            i.to_string(),
                            validation::leaf("validation_field_type_change", "Field type cannot be changed."),
                        );
                    }
                }
            }
            if let Some(err) = validation::branch(errs) {
                return Some(err);
            }
        }
    }

    if c.kind == TYPE_AUTH {
        let mut errs = Errors::new();
        for (i, field) in list.items().iter().enumerate() {
            if fields::RESERVED_AUTH_KEYS.contains(&fields::field_name(field)) {
                let mut inner = Errors::new();
                inner.insert(
                    "name".into(),
                    validation::leaf(
                        "validation_reserved_field_name",
                        "The field name is reserved and cannot be used.",
                    ),
                );
                errs.insert(i.to_string(), Node::Branch(inner));
            }
        }
        if let Some(err) = validation::branch(errs) {
            return Some(err);
        }
    }

    let mut errs = Errors::new();
    for (i, field) in list.items().iter().enumerate() {
        let field_errs = fields::validate_settings(field, c, all);
        if !field_errs.is_empty() {
            errs.insert(i.to_string(), Node::Branch(field_errs));
        }
    }
    validation::branch(errs)
}

fn check_field_duplicates(list: &FieldsList) -> Option<Node> {
    let mut ids: Vec<String> = Vec::new();
    let mut names: Vec<String> = Vec::new();

    for (i, field) in list.items().iter().enumerate() {
        let id = fields::field_id(field).to_string();
        if ids.contains(&id) {
            let mut inner = Errors::new();
            inner.insert(
                "id".into(),
                validation::leaf(
                    "validation_duplicated_field_id",
                    format!("Duplicated or invalid field id \"{id}\""),
                ),
            );
            let mut errs = Errors::new();
            errs.insert(i.to_string(), Node::Branch(inner));
            return validation::branch(errs);
        }

        let name = fields::field_name(field);
        let name_lower = name.to_lowercase();
        if names.contains(&name_lower) {
            let mut inner = Errors::new();
            inner.insert(
                "name".into(),
                validation::leaf_with_params(
                    "validation_duplicated_field_name",
                    "Duplicated or invalid field name {{.fieldName}}",
                    json!({ "fieldName": name }),
                ),
            );
            let mut errs = Errors::new();
            errs.insert(i.to_string(), Node::Branch(inner));
            return validation::branch(errs);
        }

        ids.push(id);
        names.push(name_lower);
    }
    None
}

fn check_min_fields(list: &FieldsList, c: &Collection) -> Option<Node> {
    if list.is_empty() {
        return Some(validation::required());
    }

    let id_ok = list
        .get_by_name(fields::FIELD_NAME_ID)
        .map(|field| fields::field_type(field) == "text" && fields::field_bool(field, "primaryKey"))
        .unwrap_or(false);
    if !id_ok {
        return Some(validation::leaf(
            "validation_missing_primary_key",
            "Missing or invalid \"id\" PK field.",
        ));
    }

    if c.kind != TYPE_AUTH {
        return None;
    }

    let check = |list: &FieldsList, name: &str, kind: &str, err: Node| -> Option<Node> {
        match list.get_by_name(name) {
            None => Some(err),
            Some(field) if fields::field_type(field) != kind => Some(err),
            Some(_) => None,
        }
    };
    if let Some(err) = check(
        list,
        fields::FIELD_NAME_PASSWORD,
        "password",
        validation::leaf(
            "validation_missing_password_field",
            "System \"password\" field is required.",
        ),
    ) {
        return Some(err);
    }
    if let Some(err) = check(
        list,
        fields::FIELD_NAME_TOKEN_KEY,
        "text",
        validation::leaf(
            "validation_missing_tokenKey_field",
            "System \"tokenKey\" field is required.",
        ),
    ) {
        return Some(err);
    }
    if let Some(err) = check(
        list,
        fields::FIELD_NAME_EMAIL,
        "email",
        validation::leaf(
            "validation_missing_email_field",
            "System \"email\" field is required.",
        ),
    ) {
        return Some(err);
    }
    if let Some(err) = check(
        list,
        fields::FIELD_NAME_EMAIL_VISIBILITY,
        "bool",
        validation::leaf(
            "validation_missing_emailVisibility_field",
            "System \"emailVisibility\" field is required.",
        ),
    ) {
        return Some(err);
    }
    if let Some(err) = check(
        list,
        fields::FIELD_NAME_VERIFIED,
        "bool",
        validation::leaf(
            "validation_missing_verified_field",
            "System \"verified\" field is required.",
        ),
    ) {
        return Some(err);
    }

    // System flag checks. `initDefaultFields` already enforces them, so these
    // only fire for hand-crafted input; kept for parity with `checkMinFields`.
    let system_and_hidden = |name: &str| {
        let field = list.get_by_name(name).expect("checked above");
        !(fields::field_bool(field, "hidden") && fields::field_bool(field, "system"))
    };
    for name in [fields::FIELD_NAME_PASSWORD, fields::FIELD_NAME_TOKEN_KEY] {
        if system_and_hidden(name) {
            let mut inner = Errors::new();
            inner.insert(
                name.into(),
                validation::leaf(
                    "validation_must_be_system_and_hidden",
                    "The field must be marked as \"System\" and \"Hidden\".",
                ),
            );
            return validation::branch(inner);
        }
    }
    for name in [
        fields::FIELD_NAME_EMAIL,
        fields::FIELD_NAME_EMAIL_VISIBILITY,
        fields::FIELD_NAME_VERIFIED,
    ] {
        let field = list.get_by_name(name).expect("checked above");
        if !fields::field_bool(field, "system") {
            let mut inner = Errors::new();
            inner.insert(
                name.into(),
                validation::leaf(
                    "validation_must_be_system",
                    "The field must be marked as \"System\".",
                ),
            );
            return validation::branch(inner);
        }
    }

    None
}

fn validate_indexes(conn: &Connection, c: &Collection, original: Option<&Collection>) -> Option<Node> {
    let indexes = c.index_list();

    if c.kind == TYPE_VIEW && !indexes.is_empty() {
        return Some(validation::leaf(
            "validation_indexes_not_supported",
            "View collections don't support indexes.",
        ));
    }

    let mut duplicated_names: Vec<String> = Vec::new();
    let mut duplicated_definitions: Vec<String> = Vec::new();

    for (i, raw) in indexes.iter().enumerate() {
        let mut parsed = schema_sync::parse_index(raw);
        parsed.table_name = "validator".into();
        if !parsed.is_valid() {
            return Some(index_error(
                i,
                validation::leaf(
                    "validation_invalid_index_expression",
                    "Invalid CREATE INDEX expression.",
                ),
            ));
        }

        let lower_name = parsed.index_name.to_lowercase();
        if duplicated_names.contains(&lower_name) {
            return Some(index_error(
                i,
                validation::leaf(
                    "validation_duplicated_index_name",
                    "The index name already exists.",
                ),
            ));
        }
        duplicated_names.push(lower_name);

        // the index name must not be used by another collection
        let exclude_original = original.map(|o| o.name.clone()).unwrap_or_default();
        let used_table: Option<String> = conn
            .query_row(
                "SELECT tbl_name FROM sqlite_master
                 WHERE type = 'index'
                   AND LOWER(tbl_name) != LOWER(?1)
                   AND LOWER(tbl_name) != LOWER(?2)
                   AND LOWER(name) = LOWER(?3)
                 LIMIT 1",
                rusqlite::params![exclude_original, c.name, parsed.index_name],
                |row| row.get(0),
            )
            .ok();
        if let Some(table) = used_table.filter(|t| !t.is_empty()) {
            return Some(index_error(
                i,
                validation::leaf_with_params(
                    "validation_existing_index_name",
                    "The index name is already used in {{.usedTableName}} collection.",
                    json!({ "usedTableName": table }),
                ),
            ));
        }

        parsed.schema_name = "validator".into();
        parsed.index_name = "validator".into();
        let definition = parsed.build();
        if duplicated_definitions.contains(&definition) {
            return Some(index_error(
                i,
                validation::leaf(
                    "validation_duplicated_index_definition",
                    "The index definition already exists.",
                ),
            ));
        }
        duplicated_definitions.push(definition);
    }

    // required indexes for auth collections
    if c.kind == TYPE_AUTH {
        let required_names = [fields::FIELD_NAME_TOKEN_KEY, fields::FIELD_NAME_EMAIL];
        for name in required_names {
            if schema_sync::find_single_column_unique_index(&indexes, name).is_none() {
                return Some(validation::leaf_with_params(
                    "validation_missing_required_unique_index",
                    "Missing required unique index for field \"{{.fieldName}}\".",
                    json!({ "fieldName": name }),
                ));
            }
        }
    }

    // unique system field indexes must be preserved on update
    if let Some(original) = original {
        'old_loop: for old_index in original.index_list() {
            let mut old_parsed = schema_sync::parse_index(&old_index);
            if !old_parsed.unique {
                continue;
            }
            for col in &mut old_parsed.columns {
                col.collate.clear();
                col.sort.clear();
            }
            let old_str = old_parsed.build();
            for column in &old_parsed.columns {
                for f in original.field_list().items() {
                    if !fields::field_bool(f, "system")
                        || !column.name.eq_ignore_ascii_case(fields::field_name(f))
                    {
                        continue;
                    }
                    let mut has_match = false;
                    for new_index in c.index_list() {
                        let mut new_parsed = schema_sync::parse_index(&new_index);
                        new_parsed.schema_name = old_parsed.schema_name.clone();
                        new_parsed.index_name = old_parsed.index_name.clone();
                        new_parsed.table_name = old_parsed.table_name.clone();
                        new_parsed.where_expr = old_parsed.where_expr.clone();
                        for col in &mut new_parsed.columns {
                            col.collate.clear();
                            col.sort.clear();
                        }
                        if old_str == new_parsed.build() {
                            has_match = true;
                            break;
                        }
                    }
                    if !has_match {
                        return Some(validation::leaf_with_params(
                            "validation_invalid_unique_system_field_index",
                            "Unique index definition on system fields ({{.fieldName}}) is invalid or missing.",
                            json!({ "fieldName": fields::field_name(f) }),
                        ));
                    }
                    continue 'old_loop;
                }
            }
        }
    }

    None
}

fn index_error(index: usize, node: Node) -> Node {
    let mut errs = Errors::new();
    errs.insert(index.to_string(), node);
    Node::Branch(errs)
}

