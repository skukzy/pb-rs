/// Token option keys whose `secret` is `omitempty` (and redacted on read).
const TOKEN_CONFIG_KEYS: &[&str] = &[
    "authToken",
    "passwordResetToken",
    "emailChangeToken",
    "verificationToken",
    "fileToken",
];

/// `setDefaultAuthOptions()`: the recorded template with fresh 50-char secrets.
fn auth_options_default() -> Value {
    let mut options: Value =
        serde_json::from_str(crate::assets::AUTH_OPTIONS_TEMPLATE).expect("auth options asset");
    if let Some(obj) = options.as_object_mut() {
        for key in [
            "authToken",
            "passwordResetToken",
            "emailChangeToken",
            "verificationToken",
            "fileToken",
        ] {
            if let Some(config) = obj.get_mut(key).and_then(Value::as_object_mut) {
                config.insert("secret".into(), Value::String(ids::random_string(50)));
            }
        }
    }
    options
}

fn set_option(c: &mut Collection, key: &str, value: Value) {
    if let Some(obj) = c.options.as_object_mut() {
        obj.insert(key.to_string(), value);
    }
}

/// The `Collection` struct always embeds `collectionAuthOptions`, even for
/// non-auth factories (where it is the zero value). Seed the recorded defaults
/// so a base/view body that carries auth keys binds like the oracle.
fn ensure_auth_options(c: &mut Collection) {
    if c.options.get("authToken").is_some() {
        return;
    }
    let template: Value =
        serde_json::from_str(crate::assets::AUTH_OPTIONS_TEMPLATE).expect("auth options asset");
    if let (Some(target), Some(defaults)) = (c.options.as_object_mut(), template.as_object()) {
        for (key, value) in defaults {
            target.entry(key.clone()).or_insert_with(|| value.clone());
        }
    }
}

fn option_mut<'a>(c: &'a mut Collection, key: &str) -> &'a mut Value {
    let obj = c
        .options
        .as_object_mut()
        .expect("options is always an object");
    obj.entry(key.to_string()).or_insert(Value::Null)
}

/// The zero value of each option struct (what json/v2 stores for a JSON
/// `null`). Key order follows the Go struct declaration.
fn zero_option(key: &str) -> Value {
    match key {
        "authAlert" => json!({
            "enabled": false,
            "emailTemplate": {"subject": "", "body": ""},
        }),
        "oauth2" => json!({
            "providers": [],
            "mappedFields": {"id": "", "name": "", "username": "", "avatarURL": ""},
            "enabled": false,
        }),
        "passwordAuth" => json!({"enabled": false, "identityFields": []}),
        "mfa" => json!({"enabled": false, "duration": 0, "rule": ""}),
        "otp" => json!({
            "enabled": false,
            "duration": 0,
            "length": 0,
            "emailTemplate": {"subject": "", "body": ""},
        }),
        "authToken" | "passwordResetToken" | "emailChangeToken" | "verificationToken"
        | "fileToken" => json!({"secret": "", "duration": 0}),
        "verificationTemplate" | "resetPasswordTemplate" | "confirmEmailChangeTemplate" => {
            json!({"subject": "", "body": ""})
        }
        _ => Value::Null,
    }
}

fn bind_auth_option(c: &mut Collection, key: &str, value: &Value) -> Result<(), BindError> {
    if value.is_null() {
        match key {
            "authRule" | "manageRule" => set_option(c, key, Value::Null),
            _ => *option_mut(c, key) = zero_option(key),
        }
        return Ok(());
    }
    match key {
        "authRule" | "manageRule" => {
            let bound = bind_opt_string(value)?;
            set_option(
                c,
                key,
                match bound {
                    Some(s) => Value::String(s),
                    None => Value::Null,
                },
            );
            Ok(())
        }
        "authAlert" => bind_auth_alert(option_mut(c, key), value),
        "oauth2" => bind_oauth2(option_mut(c, key), value),
        "passwordAuth" => bind_password_auth(option_mut(c, key), value),
        "mfa" => bind_mfa(option_mut(c, key), value),
        "otp" => bind_otp(option_mut(c, key), value),
        "authToken" | "passwordResetToken" | "emailChangeToken" | "verificationToken"
        | "fileToken" => bind_token_config(option_mut(c, key), value),
        "verificationTemplate" | "resetPasswordTemplate" | "confirmEmailChangeTemplate" => {
            bind_email_template(option_mut(c, key), value)
        }
        _ => Ok(()),
    }
}

fn as_object<'a>(value: &'a Value) -> Result<&'a Map<String, Value>, BindError> {
    value.as_object().ok_or(BindError)
}

/// `json.Unmarshal` into a struct: `null` zeroes it, non-objects fail.
fn merge_struct(
    target: &mut Value,
    value: &Value,
    fields: &[(&str, Option<&[(&str, Value)]>)],
) -> Result<(), BindError> {
    if value.is_null() {
        *target = Value::Object(Map::new());
        return Ok(());
    }
    let source = as_object(value)?;
    let _ = fields;
    for (key, raw) in source {
        let Some(slot) = target.get_mut(key.as_str()) else {
            continue; // unknown keys are ignored
        };
        match slot {
            Value::String(_) => *slot = Value::String(bind_string(raw)?),
            Value::Bool(_) => *slot = Value::Bool(bind_bool(raw)?),
            Value::Number(_) => *slot = Value::from(bind_i64(raw)?),
            // slices/maps: `null` sets them to nil (serialized as [] / {})
            Value::Array(_) => *slot = bind_string_array(raw)?,
            Value::Object(_) => {
                *slot = match raw {
                    Value::Null => Value::Object(Map::new()),
                    Value::Object(obj) => Value::Object(obj.clone()),
                    _ => return Err(BindError),
                }
            }
            _ => {}
        }
    }
    Ok(())
}

fn bind_email_template(target: &mut Value, value: &Value) -> Result<(), BindError> {
    if value.is_null() {
        *target = zero_option("verificationTemplate");
        return Ok(());
    }
    merge_struct(target, value, &[])
}

fn bind_auth_alert(target: &mut Value, value: &Value) -> Result<(), BindError> {
    if value.is_null() {
        *target = zero_option("authAlert");
        return Ok(());
    }
    let source = as_object(value)?;
    for (key, raw) in source {
        match key.as_str() {
            "enabled" => {
                if let Some(obj) = target.as_object_mut() {
                    obj.insert("enabled".into(), Value::Bool(bind_bool(raw)?));
                }
            }
            "emailTemplate" => {
                if let Some(template) = target.get_mut("emailTemplate") {
                    bind_email_template(template, raw)?;
                }
            }
            _ => {}
        }
    }
    Ok(())
}

