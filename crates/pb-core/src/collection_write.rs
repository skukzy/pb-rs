/// `app.ImportCollections`: upsert the provided collection definitions in a
/// single transaction, optionally deleting non-system collections that are
/// missing from the import.
pub fn import_collections(
    conn: &mut Connection,
    to_import: &[Value],
    delete_missing: bool,
) -> Result<(), SaveError> {
    if to_import.is_empty() {
        return Err(SaveError::Raw("no collections to import".into()));
    }

    // Normalize: load existing or build a factory, then bind.
    let mut imported: Vec<Draft> = Vec::with_capacity(to_import.len());
    let mut imported_ids: std::collections::HashSet<String> = std::collections::HashSet::new();
    for data in to_import {
        let (kind, name) = factory_extract(data).map_err(|_| SaveError::Raw("invalid collection data".into()))?;
        let kind = if kind.is_empty() { TYPE_BASE.to_string() } else { kind };
        let name = if name.is_empty() {
            // fall back to id
            data.get("id")
                .and_then(Value::as_str)
                .unwrap_or("")
                .to_string()
        } else {
            name
        };

        let all = Collection::load_all(conn).map_err(|e| SaveError::Raw(e.to_string()))?;
        let existing = all.iter().find(|c| {
            let ident = data.get("id").and_then(Value::as_str).unwrap_or("");
            if !ident.is_empty() && c.id == ident {
                return true;
            }
            let name_ident = data.get("name").and_then(Value::as_str).unwrap_or("");
            !name_ident.is_empty() && c.name.eq_ignore_ascii_case(name_ident)
        });

        let mut draft = if let Some(existing) = existing {
            Draft {
                collection: existing.clone(),
                autogenerated_id: existing.id.clone(),
            }
        } else {
            factory(&kind, &name)
        };

        apply_request(&mut draft, data).map_err(|_| SaveError::Raw("invalid collection data".into()))?;

        // ensure type defaults to the bound value
        if draft.collection.kind.is_empty() {
            draft.collection.kind = kind;
        }
        if draft.collection.name.is_empty() {
            draft.collection.name = name;
        }

        imported_ids.insert(draft.collection.id.clone());
        imported.push(draft);
    }

    // views last
    imported.sort_by(|a, b| {
        let a_view = a.collection.is_view();
        let b_view = b.collection.is_view();
        if a_view != b_view {
            return a_view.cmp(&b_view);
        }
        a.collection.created.cmp(&b.collection.created)
    });

    // delete missing (non-system) collections first
    if delete_missing {
        let all = Collection::load_all(conn).map_err(|e| SaveError::Raw(e.to_string()))?;
        for existing in &all {
            if existing.system {
                continue;
            }
            if imported_ids.contains(&existing.id) {
                continue;
            }
            delete(conn, existing).map_err(|e| SaveError::Raw(e))?;
        }
    }

    let all = Collection::load_all(conn).map_err(|e| SaveError::Raw(e.to_string()))?;

    for draft in &mut imported {
        let original = all.iter().find(|c| c.id == draft.collection.id).cloned();
        let result = if let Some(orig) = original {
            save_update(conn, draft, &orig, &all)
        } else {
            save(conn, draft, &all)
        };
        match result {
            Ok(()) => {}
            Err(SaveError::Validation(errors)) => {
                // `collection_import.go`: the per-collection validation tree is
                // JSON-serialized (raw messages, two-space indent) into one
                // `collections` leaf.
                let serialized =
                    serde_json::to_string_pretty(&validation::errors_to_log_value(&errors))
                        .unwrap_or_default();
                let mut wrapped = validation::Errors::new();
                wrapped.insert(
                    "collections".into(),
                    validation::leaf(
                        "validation_collections_import_failure",
                        format!(
                            "Data validations failed for collection {} ({}):\n{}",
                            crate::fields::go_quote(&draft.collection.name),
                            draft.collection.id,
                            serialized
                        ),
                    ),
                );
                return Err(SaveError::Validation(wrapped));
            }
            Err(err) => return Err(err),
        }
    }

    Collection::invalidate_cache();
    Ok(())
}

/// `FindCollectionReferences`: relation fields pointing at `collection`.
pub fn find_references(collection: &Collection, all: &[Collection]) -> Vec<String> {
    let mut names = Vec::new();
    for other in all {
        if other.id == collection.id {
            continue;
        }
        let references = other.field_list().items().iter().any(|field| {
            fields::field_type(field) == "relation"
                && fields::field_str(field, "collectionId") == collection.id
        });
        if references {
            names.push(other.name.clone());
        }
    }
    names
}

/// `onCollectionDeleteExecute` (table/view drop + row delete).
pub fn delete(conn: &mut Connection, collection: &Collection) -> Result<(), String> {
    if collection.system {
        return Err(format!(
            "[{}] system collections cannot be deleted",
            collection.name
        ));
    }

    // `onCollectionDeleteExecute`: relation references block the delete.
    let all = Collection::load_all(conn).map_err(|e| e.to_string())?;
    let references = find_references(collection, &all);
    if !references.is_empty() {
        return Err(format!(
            "[{}] failed to delete due to existing relation references: {}",
            collection.name,
            references.join(", ")
        ));
    }

    let tx = conn.transaction().map_err(|e| e.to_string())?;
    if collection.is_view() {
        tx.execute_batch(&format!(
            "DROP VIEW IF EXISTS {}",
            quote_ident(&collection.name)
        ))
        .map_err(|e| e.to_string())?;
    } else {
        schema_sync::drop_table(&tx, collection).map_err(|e| e.to_string())?;
    }

    // `onCollectionDeleteExecute`: trigger a views resave to detect broken
    // view dependencies before deleting the collection row.
    if let Err(err) =
        resave_views_with_changed_fields_tx(&tx, std::slice::from_ref(&collection.id))
    {
        return Err(format!(
            "[{}] failed to delete due to existing view dependency: {}",
            collection.name, err
        ));
    }

    tx.execute("DELETE FROM _collections WHERE id = ?1", [&collection.id])
        .map_err(|e| e.to_string())?;
    tx.commit().map_err(|e| e.to_string())?;
    Collection::invalidate_cache();
    Ok(())
}

fn quote_ident(name: &str) -> String {
    format!("`{}`", name.replace('`', "``"))
}

/// `app.TruncateCollection`: delete the records in batches of 500 through the
/// regular record delete path, so relation cascades and the superuser guard
/// behave exactly like the oracle. The whole operation runs in a savepoint.
pub fn truncate(
    conn: &mut Connection,
    collection: &Collection,
) -> Result<(), crate::record_delete::DeleteError> {
    use crate::record_delete::{delete_record_in_savepoint, DeleteError};
    use crate::record_upsert::RecordModel;

    if collection.is_view() {
        return Err(DeleteError::Raw(
            "view collections cannot be truncated since they don't store their own records".into(),
        ));
    }

    let all = Collection::load_all(conn).map_err(|e| DeleteError::Raw(e.to_string()))?;
    conn.execute_batch("SAVEPOINT pb_truncate")
        .map_err(|e| DeleteError::Raw(e.to_string()))?;

    let mut deleted = Vec::new();
    let result = (|| -> Result<(), DeleteError> {
        loop {
            let ids: Vec<String> = {
                let sql = format!(
                    "SELECT id FROM {} LIMIT 500",
                    quote_ident(&collection.name)
                );
                let mut stmt = conn
                    .prepare(&sql)
                    .map_err(|e| DeleteError::Raw(e.to_string()))?;
                let mut rows = stmt
                    .query([])
                    .map_err(|e| DeleteError::Raw(e.to_string()))?;
                let mut ids = Vec::new();
                while let Some(row) = rows
                    .next()
                    .map_err(|e| DeleteError::Raw(e.to_string()))?
                {
                    ids.push(
                        row.get::<_, String>(0)
                            .map_err(|e| DeleteError::Raw(e.to_string()))?,
                    );
                }
                ids
            };

            if ids.is_empty() {
                break;
            }

            for id in ids {
                let Some(record) = RecordModel::find_by_id(conn, collection, &id)
                    .map_err(|e| DeleteError::Raw(e.to_string()))?
                else {
                    // A cascade deleted it after the batch query.
                    continue;
                };
                delete_record_in_savepoint(conn, &all, collection, &record, &mut deleted)?;
            }
        }
        Ok(())
    })();

    match result {
        Ok(()) => {
            conn.execute_batch("RELEASE pb_truncate")
                .map_err(|e| DeleteError::Raw(e.to_string()))?;
            Ok(())
        }
        Err(err) => {
            let _ = conn.execute_batch("ROLLBACK TO pb_truncate; RELEASE pb_truncate");
            Err(err)
        }
    }
}

/// `collectionValidator.checkRule`: ensure a rule expression parses and every
/// referenced field resolves against the collection schema.
fn validate_rule(
    c: &Collection,
    rule: &str,
    all: &[Collection],
) -> Result<(), String> {
    use std::collections::HashMap;

    let by_id: HashMap<&str, &Collection> = all.iter().map(|col| (col.id.as_str(), col)).collect();

    let relations_for = |col: &Collection| -> HashMap<String, search::RelationInfo> {
        let mut relations = HashMap::new();
        for f in col.field_list().items() {
            if fields::field_type(f) == "relation" {
                let coll_id = fields::field_str(f, "collectionId");
                if let Some(target) = by_id.get(coll_id) {
                    relations.insert(
                        fields::field_name(f).to_string(),
                        search::RelationInfo {
                            table: target.name.clone(),
                            multiple: fields::is_multiple(f),
                        },
                    );
                }
            }
        }
        relations
    };

    let info_for = |col: &Collection| -> search::CollectionInfo {
        let mut field_types = HashMap::new();
        let mut hidden = std::collections::HashSet::new();
        for f in col.field_list().items() {
            let name = fields::field_name(f).to_string();
            field_types.insert(name.clone(), fields::field_type(f).to_string());
            if fields::field_bool(f, "hidden") {
                hidden.insert(name);
            }
        }
        field_types.insert("id".to_string(), "text".to_string());
        search::CollectionInfo {
            table: col.name.clone(),
            fields: col
                .field_list()
                .items()
                .iter()
                .map(|f| fields::field_name(f).to_string())
                .chain(std::iter::once("id".to_string()))
                .collect(),
            field_types,
            hidden,
            relations: relations_for(col),
        }
    };

    let mut collections: HashMap<String, search::CollectionInfo> = HashMap::new();
    for col in all {
        let info = info_for(col);
        collections.insert(col.name.clone(), info.clone());
        collections.insert(col.id.clone(), info);
    }

    // `checkRule` resolves against the *draft* collection (validator.new),
    // which may not be part of `all` yet (create) or still be the old version
    // (update).
    let base = info_for(c);
    collections.insert(c.name.clone(), base.clone());
    collections.insert(c.id.clone(), base.clone());

    let relations = base.relations.clone();
    let allowed: Vec<String> = base.fields.clone();

    let empty_request = search::RequestData::default();
    let types = search::RequestFieldTypes::default();

    let expr = search::parse(rule).map_err(|e| e.0)?;
    search::validate_record_expr(&expr, &base, &collections).map_err(|e| e.0)?;
    let expr = search::resolve_request_fields(&expr, &empty_request, &types).map_err(|e| e.0)?;
    search::build_sql_full_with_types(
        &expr,
        &allowed,
        None,
        &relations,
        &collections,
        &base.field_types,
    )
    .map(|_| ())
    .map_err(|e| e.0)
}

