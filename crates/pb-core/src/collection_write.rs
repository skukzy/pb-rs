/// The factory defaults of a type, used by `ensureNoFieldsTypeChange` for new
/// collections (`newCollectionValidator` builds `NewCollection(type, "")`).
fn factory_fields(kind: &str) -> Vec<Value> {
    factory(kind, "").collection.field_list().items().to_vec()
}

fn init_default_fields(c: &mut Collection, list: &mut FieldsList) {
    match c.kind.as_str() {
        TYPE_BASE => init_id_field(list),
        TYPE_AUTH => {
            init_id_field(list);
            init_password_field(list);
            init_token_key_field(list, c);
            init_email_field(list, c);
            init_email_visibility_field(list);
            init_verified_field(list);
        }
        // view fields are generated from the query
        _ => {}
    }
}

fn init_id_field(list: &mut FieldsList) {
    if let Some(field) = list.get_by_name(fields::FIELD_NAME_ID) {
        if fields::field_type(field) == "text" {
            if let Some(field) = list.get_by_name_mut(fields::FIELD_NAME_ID) {
                fields::set_bool(field, "system", true);
                fields::set_bool(field, "required", true);
                fields::set_bool(field, "primaryKey", true);
                fields::set_bool(field, "hidden", false);
                if fields::field_str(field, "pattern").is_empty() {
                    fields::set_str(field, "pattern", "^[a-z0-9]+$");
                }
            }
            return;
        }
    }

    let field = fields::from_request(&json!({
        "name": "id",
        "type": "text",
        "system": true,
        "primaryKey": true,
        "required": true,
        "min": 15,
        "max": 15,
        "pattern": "^[a-z0-9]+$",
        "autogeneratePattern": "[a-z0-9]{15}",
    }))
    .expect("default id field");
    list.prepend(field);
}

fn init_password_field(list: &mut FieldsList) {
    if let Some(field) = list.get_by_name(fields::FIELD_NAME_PASSWORD) {
        if fields::field_type(field) == "password" {
            if let Some(field) = list.get_by_name_mut(fields::FIELD_NAME_PASSWORD) {
                fields::set_bool(field, "system", true);
                fields::set_bool(field, "hidden", true);
                fields::set_bool(field, "required", true);
            }
            return;
        }
    }
    list.add(
        fields::from_request(&json!({
            "name": fields::FIELD_NAME_PASSWORD,
            "type": "password",
            "system": true,
            "hidden": true,
            "required": true,
            "min": 8,
        }))
        .expect("default password field"),
    );
}

fn init_token_key_field(list: &mut FieldsList, c: &mut Collection) {
    if let Some(field) = list.get_by_name(fields::FIELD_NAME_TOKEN_KEY) {
        if fields::field_type(field) == "text" {
            if let Some(field) = list.get_by_name_mut(fields::FIELD_NAME_TOKEN_KEY) {
                fields::set_bool(field, "system", true);
                fields::set_bool(field, "hidden", true);
                fields::set_bool(field, "required", true);
            }
        } else {
            list.add(
                fields::from_request(&json!({
                    "name": fields::FIELD_NAME_TOKEN_KEY,
                    "type": "text",
                    "system": true,
                    "hidden": true,
                    "min": 30,
                    "max": 60,
                    "required": true,
                    "autogeneratePattern": "[a-zA-Z0-9]{50}",
                }))
                .expect("default tokenKey field"),
            );
        }
    } else {
        list.add(
            fields::from_request(&json!({
                "name": fields::FIELD_NAME_TOKEN_KEY,
                "type": "text",
                "system": true,
                "hidden": true,
                "min": 30,
                "max": 60,
                "required": true,
                "autogeneratePattern": "[a-zA-Z0-9]{50}",
            }))
            .expect("default tokenKey field"),
        );
    }

    let mut indexes = c.index_list();
    if schema_sync::find_single_column_unique_index(&indexes, fields::FIELD_NAME_TOKEN_KEY)
        .is_none()
    {
        indexes.push(format!(
            "CREATE UNIQUE INDEX `{}` ON `{}` (`{}`)",
            field_index_name(c, fields::FIELD_NAME_TOKEN_KEY),
            c.name,
            fields::FIELD_NAME_TOKEN_KEY
        ));
        set_indexes(c, indexes);
    }
}

fn init_email_field(list: &mut FieldsList, c: &mut Collection) {
    if let Some(field) = list.get_by_name(fields::FIELD_NAME_EMAIL) {
        if fields::field_type(field) == "email" {
            if let Some(field) = list.get_by_name_mut(fields::FIELD_NAME_EMAIL) {
                fields::set_bool(field, "system", true);
                fields::set_bool(field, "hidden", false);
            }
        } else {
            list.add(
                fields::from_request(&json!({
                    "name": fields::FIELD_NAME_EMAIL,
                    "type": "email",
                    "system": true,
                    "required": true,
                }))
                .expect("default email field"),
            );
        }
    } else {
        list.add(
            fields::from_request(&json!({
                "name": fields::FIELD_NAME_EMAIL,
                "type": "email",
                "system": true,
                "required": true,
            }))
            .expect("default email field"),
        );
    }

    let mut indexes = c.index_list();
    if schema_sync::find_single_column_unique_index(&indexes, fields::FIELD_NAME_EMAIL).is_none() {
        indexes.push(format!(
            "CREATE UNIQUE INDEX `{}` ON `{}` (`{}`) WHERE `{}` != ''",
            field_index_name(c, fields::FIELD_NAME_EMAIL),
            c.name,
            fields::FIELD_NAME_EMAIL,
            fields::FIELD_NAME_EMAIL
        ));
        set_indexes(c, indexes);
    }
}

fn init_email_visibility_field(list: &mut FieldsList) {
    init_system_bool(list, fields::FIELD_NAME_EMAIL_VISIBILITY);
}

fn init_verified_field(list: &mut FieldsList) {
    init_system_bool(list, fields::FIELD_NAME_VERIFIED);
}

fn init_system_bool(list: &mut FieldsList, name: &str) {
    if let Some(field) = list.get_by_name(name) {
        if fields::field_type(field) == "bool" {
            if let Some(field) = list.get_by_name_mut(name) {
                fields::set_bool(field, "system", true);
            }
            return;
        }
    }
    list.add(
        fields::from_request(&json!({
            "name": name,
            "type": "bool",
            "system": true,
        }))
        .expect("default bool field"),
    );
}

/// `c.fieldIndexName(field)`.
fn field_index_name(c: &Collection, field: &str) -> String {
    let suffix = if !c.id.is_empty() {
        c.id.clone()
    } else if !c.name.is_empty() {
        c.name.clone()
    } else {
        ids::random_string_with_alphabet(10, ids::ID_ALPHABET)
    };
    format!("idx_{field}_{suffix}")
}

fn set_indexes(c: &mut Collection, items: Vec<String>) {
    c.indexes = Value::Array(items.into_iter().map(Value::String).collect());
}

/// `c.unsetMissingOAuth2MappedFields()`.
fn unset_missing_oauth2_mapped_fields(c: &mut Collection, list: &FieldsList) {
    let Some(mapped) = c
        .options
        .get_mut("oauth2")
        .and_then(|o| o.get_mut("mappedFields"))
        .and_then(Value::as_object_mut)
    else {
        return;
    };
    for key in ["id", "name", "username", "avatarURL"] {
        let Some(Value::String(field_name)) = mapped.get(key) else {
            continue;
        };
        if !field_name.is_empty() && list.get_by_name(field_name).is_none() {
            mapped.insert(key.to_string(), Value::String(String::new()));
        }
    }
}

/// `c.updateGeneratedIdIfExists(app)`.
fn update_generated_id(c: &mut Collection, autogenerated_id: &str, all: &[Collection]) {
    if c.id.is_empty() || c.id != autogenerated_id {
        return;
    }

    let checksum = id_checksum(&c.kind, &c.name);
    let mut new_id = checksum.clone();
    for i in 2..1000 {
        if !all.iter().any(|other| other.id == new_id) {
            break;
        }
        new_id = format!("{checksum}{i}");
    }

    if c.id == new_id {
        return;
    }

    let mut indexes = c.index_list();
    for raw in &mut indexes {
        let mut parsed = schema_sync::parse_index(raw);
        let original = parsed.index_name.clone();
        parsed.index_name = parsed.index_name.replace(&c.id, &new_id);
        if parsed.index_name != original {
            *raw = parsed.build();
        }
    }
    set_indexes(c, indexes);
    c.id = new_id;
}

/// `onCollectionSave`.
fn normalize(draft: &mut Draft, all: &[Collection]) {
    let c = &mut draft.collection;

    if c.kind.is_empty() {
        c.kind = TYPE_BASE.to_string();
    }

    // `IsNew()` is always true on the create path.
    if c.id.is_empty() {
        c.id = id_checksum(&c.kind, &c.name);
        draft.autogenerated_id = c.id.clone();
    }

    // `Fields = NewFieldsList(Fields...)`
    let mut list = c.field_list();
    list.renormalize();
    c.fields = list.to_json();

    let mut list = c.field_list();
    init_default_fields(c, &mut list);
    c.fields = list.to_json();

    if c.kind == TYPE_AUTH {
        unset_missing_oauth2_mapped_fields(c, &list);
    }

    update_generated_id(c, &draft.autogenerated_id, all);

    c.indexes = Value::Array(
        schema_sync::normalize_indexes(&c.name, c.index_list_values())
            .into_iter()
            .map(Value::String)
            .collect(),
    );
}

fn normalize_update(draft: &mut Draft, original: &Collection) {
    let c = &mut draft.collection;

    if c.kind.is_empty() {
        c.kind = TYPE_BASE.to_string();
    }

    // created is preserved; only Updated is refreshed.
    if c.created.is_empty() {
        c.created = original.created.clone();
    }

    let mut list = c.field_list();
    list.renormalize();
    c.fields = list.to_json();

    let mut list = c.field_list();
    init_default_fields(c, &mut list);
    c.fields = list.to_json();

    if c.kind == TYPE_AUTH {
        unset_missing_oauth2_mapped_fields(c, &list);
    }

    c.indexes = Value::Array(
        schema_sync::normalize_indexes(&c.name, c.index_list_values())
            .into_iter()
            .map(Value::String)
            .collect(),
    );
}

trait IndexValues {
    fn index_list_values(&self) -> &[Value];
}

impl IndexValues for Collection {
    fn index_list_values(&self) -> &[Value] {
        self.indexes.as_array().map(Vec::as_slice).unwrap_or(&[])
    }
}

